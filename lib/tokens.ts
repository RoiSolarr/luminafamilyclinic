import { createHash, randomBytes, randomInt, timingSafeEqual, createHmac } from 'node:crypto'
import { clinic } from '@/config/clinic'

/**
 * Secrets, references and link signing. Server side only.
 *
 * Manage tokens are never stored in plain text. The database holds a SHA-256
 * digest; the raw token exists only in the success screen, the confirmation
 * email and the patient's link.
 */

/** Characters that cannot be confused with each other when read aloud. */
const REF_ALPHABET = 'ACDEFGHJKLMNPQRTUVWXY34679'

/** A booking reference such as LFC-K7M2QD. */
export function generateBookingRef(prefix: string = clinic.bookingRefPrefix): string {
  let body = ''
  for (let i = 0; i < 6; i++) {
    body += REF_ALPHABET[randomInt(0, REF_ALPHABET.length)]
  }
  return `${prefix}-${body}`
}

/** A 32 character URL safe token the patient keeps. */
export function generateManageToken(): string {
  return randomBytes(24).toString('base64url').slice(0, 32)
}

/** SHA-256 digest, hex encoded. What actually goes in the database. */
export function hashToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex')
}

/** Compare two strings without leaking their difference through timing. */
export function safeEqual(a: string | undefined | null, b: string | undefined | null): boolean {
  if (!a || !b) return false
  // Hash both first so the comparison always runs over equal length buffers,
  // which keeps the timing constant even when the lengths differ.
  const ba = createHash('sha256').update(a, 'utf8').digest()
  const bb = createHash('sha256').update(b, 'utf8').digest()
  return timingSafeEqual(ba, bb)
}

/** True when the supplied raw token matches a stored digest. */
export function verifyManageToken(rawToken: string, storedHash: string): boolean {
  return safeEqual(hashToken(rawToken), storedHash)
}

/**
 * Feedback links are signed rather than stored, so the post visit email can be
 * generated by an automation without writing another row first.
 * Signature = HMAC-SHA256(bookingRef, FEEDBACK_LINK_SECRET), first 32 hex chars.
 */
export function signFeedbackRef(bookingRef: string): string {
  const secret = process.env.FEEDBACK_LINK_SECRET || process.env.ZAPIER_CALLBACK_SECRET || ''
  return createHmac('sha256', secret).update(bookingRef, 'utf8').digest('hex').slice(0, 32)
}

export function verifyFeedbackSignature(bookingRef: string, signature: string): boolean {
  return safeEqual(signFeedbackRef(bookingRef), signature)
}

/** Validate the shared secret Zapier sends in the `x-zapier-secret` header. */
export function verifyZapierSecret(headerValue: string | null): boolean {
  const expected = process.env.ZAPIER_CALLBACK_SECRET
  if (!expected) return false
  return safeEqual(headerValue, expected)
}
